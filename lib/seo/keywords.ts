export type KeywordCluster = keyof typeof KEYWORDS;

/** Every term in one cluster, across all of its groups. */
export function clusterKeywords(cluster: KeywordCluster): string[] {
  return Object.values(KEYWORDS[cluster] as Record<string, readonly string[]>).flat();
}

/** Every term in the list, de-duplicated. */
export function allKeywords(): string[] {
  const out = new Set<string>();
  for (const cluster of Object.keys(KEYWORDS) as KeywordCluster[]) {
    for (const k of clusterKeywords(cluster)) out.add(k);
  }
  return [...out];
}

/**
 * Case-insensitive substring search across the whole list.
 * Useful when writing a page and you want the terms that mention, say,
 * "Imphal" or "cargo".
 */
export function findKeywords(term: string): string[] {
  const q = term.toLowerCase();
  return allKeywords().filter((k) => k.toLowerCase().includes(q));
}

/**
 * The handful of terms worth putting in a page's metadata. Long keyword
 * arrays are noise — a page should name the few things it is genuinely about.
 */
export function metaKeywords(cluster: KeywordCluster, limit = 8): string[] {
  return clusterKeywords(cluster).slice(0, limit);
}

