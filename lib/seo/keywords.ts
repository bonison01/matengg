/**
 * Keywords for a route, interleaved across its groups so the list leads with
 * the most relevant term from each rather than exhausting the first group.
 * Returns undefined for routes with no mapping (legal pages and the like),
 * which is the right value to hand straight to `buildMetadata`.
 */
export function pageKeywords(path: string, limit = 10): string[] | undefined {
  const groups = PAGE_GROUPS[path];
  if (!groups) return undefined;

  const out: string[] = [];
  const seen = new Set<string>();
  const depth = Math.max(...groups.map((g) => g.length));

  for (let i = 0; i < depth && out.length < limit; i++) {
    for (const g of groups) {
      if (out.length >= limit) break;
      const k = g[i];
      if (k && !seen.has(k)) {
        seen.add(k);
        out.push(k);
      }
    }
  }
  return out.length ? out : undefined;
}
